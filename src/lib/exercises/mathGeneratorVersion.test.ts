// The generators are a replay contract (see mathGeneratorVersion.ts). These
// tests pin what each version generates and that the server replays an attempt
// with the version stamped on it.

type Session = { name: string; generate: (seed: number, version: MathGeneratorVersion) => GeneratedQuestion[] };

const SESSIONS: Session[] = [
  { name: 'ring', generate: (seed, version) => generateKiurMathSession('ring-ja-ringjoon', 'Segaharjutus', 'Lihtne', 15, seed, version) },
  { name: 'arvud', generate: (seed, version) => generateKiurMathSession('arvud-10000-piires', 'Segaharjutus', 'Lihtne', 15, seed, version) },
  { name: 'pikkused', generate: (seed, version) => generateKiurMathSession('mootuhikud-pikkused', 'Segaharjutus', 'Lihtne', 15, seed, version) },
  { name: 'jagamine', generate: (seed, version) => generateKiurMathSession('jagamine-kahekohaline-uhekohaline', 'Segaharjutus', 'Lihtne', 15, seed, version) },
  { name: 'kirsi-kell', generate: (seed, version) => generateKirsiSession('Kellaaeg', 15, seed, version) }
];

function digest(session: Session, version: MathGeneratorVersion) {
  const hash = createHash('sha256');
  for (let seed = 1; seed <= 50; seed += 1) hash.update(JSON.stringify(session.generate(seed, version)));
  return hash.digest('hex').slice(0, 16);
}

