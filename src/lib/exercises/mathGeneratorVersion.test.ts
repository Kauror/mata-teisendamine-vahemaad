function correctAnswerOf(question: GeneratedQuestion) {
  if (question.kind === 'choice' && question.choiceOptions) return question.choiceOptions[question.correctAnswer];
  if (question.kind === 'text') return question.correctAnswerText ?? '';
  return String(question.correctAnswer);
}

function correctResults(questions: GeneratedQuestion[]) {
  const snapshot: MathAnswerSnapshot = {
    answers: questions.map((question) => question.kind === 'choice' ? '' : correctAnswerOf(question)),
    choiceAnswers: questions.map((question) => question.kind === 'choice' ? correctAnswerOf(question) : ''),
    orderingAnswers: questions.map((question) => question.kind === 'ordering'
      ? [...(question.orderingCards ?? [])].sort((a, b) => question.orderingDirection === 'desc' ? b.valueMm - a.valueMm : a.valueMm - b.valueMm).map((card) => card.id)
      : [])
  };
  return buildMathQuestionResults(questions, snapshot);
}

function verify(questions: GeneratedQuestion[], seed: number, generatorVersion: string, topic = 'ring-ja-ringjoon') {
  return recomputeScore({
    runnerId: 'math', learner: 'kiur', subject: 'matemaatika', topic, category: 'Segaharjutus', difficulty: 'Lihtne',
    seed, generatorVersion, questionIds: questions.map((question) => question.id), questions: correctResults(questions)
  });
}

describe('maths generator versions', () => {
  it('starts new sessions on the current version, which the runner contract names', () => {
    expect(MATH_GENERATOR_VERSION).toBe(MATH_GENERATOR_VERSION_V3);
    expect(getOfflineRunnerCapability('math')?.generatorVersion).toBe(MATH_GENERATOR_VERSION);
    expect(generateKiurMathSession('ring-ja-ringjoon', 'Segaharjutus', 'Lihtne', 15, 7)).toEqual(generateKiurMathSession('ring-ja-ringjoon', 'Segaharjutus', 'Lihtne', 15, 7, MATH_GENERATOR_VERSION));
    expect(generateKirsiSession('Kellaaeg', 15, 7)).toEqual(generateKirsiSession('Kellaaeg', 15, 7, MATH_GENERATOR_VERSION));
  });

  it('still supports the version every attempt made before the bump carries', () => {
    expect(MATH_GENERATOR_VERSIONS).toContain(MATH_GENERATOR_VERSION_V1);
    expect(MATH_GENERATOR_VERSION_V1).toBe('2026-07-1');
    expect(isSupportedMathGeneratorVersion('2026-07-1')).toBe(true);
    expect(MATH_GENERATOR_VERSIONS).toEqual(['2026-07-1', 'math-2026-10', 'math-2026-10b']);
    expect(isSupportedMathGeneratorVersion('math-2026-10')).toBe(true);
    expect(isSupportedMathGeneratorVersion('math-1999')).toBe(false);
  });

  it.each(SESSIONS.map((session) => [session.name, session] as const))('v1 %s still generates exactly what production generated', (name, session) => {
    expect(digest(session, MATH_GENERATOR_VERSION_V1)).toBe(V1_DIGESTS[name]);
  });

  it.each(SESSIONS.map((session) => [session.name, session] as const))('v2 %s still generates exactly what production generated', (name, session) => {
    expect(digest(session, MATH_GENERATOR_VERSION_V2)).toBe(V2_DIGESTS[name]);
  });

  it.each(SESSIONS.filter((session) => session.name !== 'jagamine').map((session) => [session.name, session] as const))('v2 %s differs from v1, so the version really selects the generator', (_name, session) => {
    expect(digest(session, MATH_GENERATOR_VERSION_V2)).not.toBe(digest(session, MATH_GENERATOR_VERSION_V1));
  });

  // v3 changes only Ring's lettered figures and «Leia arvutusviga»; the other
  // sessions are v2's, byte for byte.
  it.each(SESSIONS.map((session) => [session.name, session] as const))('v3 %s changes exactly the sessions it should', (name, session) => {
    const changed = name === 'ring' || name === 'arvud';
    if (changed) expect(digest(session, MATH_GENERATOR_VERSION_V3)).not.toBe(V2_DIGESTS[name]);
    else expect(digest(session, MATH_GENERATOR_VERSION_V3)).toBe(V2_DIGESTS[name]);
  });
});

describe('server replay by version', () => {
  it('verifies an attempt generated with the old version after the change', () => {
    for (let seed = 1; seed <= 25; seed += 1) {
      const v1 = generateKiurMathSession('ring-ja-ringjoon', 'Segaharjutus', 'Lihtne', 15, seed, MATH_GENERATOR_VERSION_V1);
      expect(verify(v1, seed, MATH_GENERATOR_VERSION_V1).score).toBe(15);
    }
  });

  it('verifies an attempt generated with the previous version (v2) after the change', () => {
    for (let seed = 1; seed <= 25; seed += 1) {
      for (const topic of ['ring-ja-ringjoon', 'arvud-10000-piires']) {
        const v2 = generateKiurMathSession(topic, 'Segaharjutus', 'Lihtne', 15, seed, MATH_GENERATOR_VERSION_V2);
        expect(verify(v2, seed, MATH_GENERATOR_VERSION_V2, topic).score).toBe(15);
      }
    }
  });

  it('verifies an attempt generated with the new version', () => {
    for (let seed = 1; seed <= 25; seed += 1) {
      for (const topic of ['ring-ja-ringjoon', 'arvud-10000-piires']) {
        const v3 = generateKiurMathSession(topic, 'Segaharjutus', 'Lihtne', 15, seed);
        expect(verify(v3, seed, MATH_GENERATOR_VERSION, topic).score).toBe(15);
      }
    }
  });

  it('does not verify a v3 attempt as if it were v2', () => {
    // Seeds where a lettered figure or «Leia arvutusviga» differs between the
    // versions: a v3 attempt answered right must not verify as v2.
    let rejected = 0;
    for (let seed = 1; seed <= 25; seed += 1) {
      const v3 = generateKiurMathSession('ring-ja-ringjoon', 'Segaharjutus', 'Lihtne', 15, seed, MATH_GENERATOR_VERSION_V3);
      try {
        if (verify(v3, seed, MATH_GENERATOR_VERSION_V2).score < 15) rejected += 1;
      } catch (error) {
        expect(error).toBeInstanceOf(AttemptContractError);
        rejected += 1;
      }
    }
    expect(rejected).toBeGreaterThan(0);
  });

  it('verifies Kirsi clock attempts of both versions', () => {
    for (const version of MATH_GENERATOR_VERSIONS) {
      const questions = generateKirsiSession('Kellaaeg', 15, 3, version);
      const verified = recomputeScore({
        runnerId: 'math', learner: 'kirsi', subject: 'matemaatika', topic: 'kellaaeg', category: 'Kellaaeg', difficulty: 'Lihtne',
        seed: 3, generatorVersion: version, questionIds: questions.map((question) => question.id), questions: correctResults(questions)
      });
      expect(verified.score).toBe(15);
    }
  });

  it('rejects an attempt replayed with the wrong or an unknown version', () => {
    const v1 = generateKiurMathSession('ring-ja-ringjoon', 'Segaharjutus', 'Lihtne', 15, 11, MATH_GENERATOR_VERSION_V1);
    expect(() => verify(v1, 11, MATH_GENERATOR_VERSION_V2)).toThrowError(AttemptContractError);
    expect(() => verify(v1, 11, 'math-1999')).toThrowError(/Unsupported math generator version/);
  });

  it('accepts either supported version against either grant snapshot, nothing else', () => {
    const contract = {
      learner: 'kiur' as const, exerciseId: 'kiur.math.ring-ja-ringjoon', catalogueVersion: 'catalogue-1', rewardPolicyVersion: 'policy-1',
      runnerVersion: 'math-v1', rotationVersion: 1, acceptedGeneratorVersions: MATH_GENERATOR_VERSIONS
    };
    const attempt = (generatorVersion: string) => ({ learner: 'kiur', exerciseId: contract.exerciseId, catalogueVersion: 'catalogue-1', rewardPolicyVersion: 'policy-1', runnerVersion: 'math-v1', rotationVersion: 1, generatorVersion });
    for (const grantVersion of MATH_GENERATOR_VERSIONS) {
      for (const attemptVersion of MATH_GENERATOR_VERSIONS) {
        expect(metadataMatchesContract(attempt(attemptVersion), { ...contract, generatorVersion: grantVersion })).toBe(true);
      }
      expect(metadataMatchesContract(attempt('math-1999'), { ...contract, generatorVersion: grantVersion })).toBe(false);
    }
    // Runners without a replay list keep the exact match.
    expect(metadataMatchesContract(attempt(MATH_GENERATOR_VERSION_V1), { ...contract, acceptedGeneratorVersions: undefined, generatorVersion: MATH_GENERATOR_VERSION_V2 })).toBe(false);
  });
});

describe('option display order (EX-04)', () => {
  const questions = generateKiurMathSession('arvud-10000-piires', 'Segaharjutus', 'Lihtne', 15, 5);

  it('is deterministic per seed and question, and a permutation', () => {
    const order = buildMathOptionOrder(questions, 5);
    expect(buildMathOptionOrder(questions, 5)).toEqual(order);
    for (const question of questions.filter((candidate) => candidate.kind === 'choice')) {
      expect([...order[question.id]].sort()).toEqual(question.choiceOptions!.map((_, index) => index));
      expect([...displayedMathOptions(question, order)].sort()).toEqual([...question.choiceOptions!].sort());
    }
  });

  it('shows a session paused before the shuffle existed in its generated order', () => {
    for (const question of questions.filter((candidate) => candidate.kind === 'choice')) {
      expect(displayedMathOptions(question, null)).toEqual(question.choiceOptions);
      expect(displayedMathOptions(question, { [question.id]: [0, 0, 1] })).toEqual(question.choiceOptions);
    }
  });

  it('cannot change scoring: answers are labels, scored the same in any display order', () => {
    const results = correctResults(questions);
    expect(results.every((result) => result.isCorrect)).toBe(true);
    expect(verify(questions, 5, MATH_GENERATOR_VERSION, 'arvud-10000-piires').score).toBe(15);
  });
});
